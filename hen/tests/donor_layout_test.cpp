template <size_t ListingCount>
u32 makeTitle(const ListedFile (&listing)[ListingCount], DonorFile* title) {
    static_assert(ListingCount <= DonorFileLimit);
    for (size_t index = 0; index < ListingCount; index++) {
        title[index] = {};
        std::strcpy(title[index].name, listing[index].name);
        title[index].size = listing[index].size;
    }
    return ListingCount;
}

u64 read64(const u8* bytes) {
    u64 value = 0;
    for (int index = 7; index >= 0; index--) value = (value << 8) | bytes[index];
    return value;
}

template <size_t ListingCount, size_t HeaderSize>
void checkCase(const char* what, const ListedFile (&listing)[ListingCount], u64 hbloader,
               const u8 (&expected)[HeaderSize], u64 expected_size) {
    DonorFile title[DonorFileLimit];
    const u32 count = makeTitle(listing, title);
    static DonorPlan plan;
    if (!planDonor(title, count, hbloader, plan)) {
        std::printf("FAIL: %s: refused\n", what);
        g_failures++;
        return;
    }
    bool same = plan.header_size == HeaderSize &&
                std::memcmp(plan.header, expected, HeaderSize) == 0;
    if (!same) {
        std::printf("FAIL: %s: header differs (size %u, expected %zu)\n", what,
                    plan.header_size, HeaderSize);
        for (size_t index = 0; index < HeaderSize && index < plan.header_size; index++) {
            if (plan.header[index] != expected[index]) {
                std::printf("  first difference at %#zx: %#04x, expected %#04x\n", index,
                            plan.header[index], expected[index]);
                break;
            }
        }
        std::printf("  order:");
        for (u32 index = 0; index < plan.count; index++) {
            std::printf(" %s", plan.files[index].name);
        }
        std::printf("\n");
        g_failures++;
    }
    if (plan.size != expected_size) {
        std::printf("FAIL: %s: package size %#llx, expected %#llx\n", what,
                    static_cast<unsigned long long>(plan.size),
                    static_cast<unsigned long long>(expected_size));
        g_failures++;
    }
    // The copy writes each file at plan.offsets: the header's data offset
    // from the end of the names, every one 32-byte aligned.
    for (u32 index = 0; same && index < plan.count; index++) {
        const u64 offset = read64(plan.header + 16 + index * 24);
        if (plan.offsets[index] != plan.header_size + offset || offset % 0x20) {
            std::printf("FAIL: %s: file %u offset\n", what, index);
            g_failures++;
        }
        if (plan.files[index].hbloader != (index == 0)) {
            std::printf("FAIL: %s: file %u source\n", what, index);
            g_failures++;
        }
    }
    expect(!std::strcmp(plan.files[0].name, "rtld") && plan.files[0].size == hbloader, what);
}

void checkLayouts() {
    checkCase("typical title", Listing_typical, Hbloader_typical, Expected_typical,
              ExpectedSize_typical);
    checkCase("unusual names", Listing_names, Hbloader_names, Expected_names, ExpectedSize_names);
    checkCase("aligned files", Listing_aligned, Hbloader_aligned, Expected_aligned,
              ExpectedSize_aligned);
    checkCase("the most files", Listing_full, Hbloader_full, Expected_full, ExpectedSize_full);
}

template <size_t ListingCount>
bool plans(const ListedFile (&listing)[ListingCount], u64 hbloader = 0x100) {
    DonorFile title[DonorFileLimit];
    const u32 count = makeTitle(listing, title);
    static DonorPlan plan;
    return planDonor(title, count, hbloader, plan);
}

void checkRefusals() {
    constexpr ListedFile no_main[] = {{"rtld", 4}, {"main.npdm", 0x20}, {"sdk", 4}};
    expect(!plans(no_main), "no main");
    constexpr ListedFile no_policy[] = {{"main", 4}, {"sdk", 4}};
    expect(!plans(no_policy), "no main.npdm");
    constexpr ListedFile repeated[] = {{"main", 4}, {"main.npdm", 0x20}, {"main", 8}};
    expect(!plans(repeated), "a repeated name");
    constexpr ListedFile separator[] = {{"main", 4}, {"main.npdm", 0x20}, {"a/b", 1}};
    expect(!plans(separator), "a name with a separator");
    constexpr ListedFile dot[] = {{"main", 4}, {"main.npdm", 0x20}, {"..", 1}};
    expect(!plans(dot), "a dot name");
    constexpr ListedFile empty[] = {{"main", 4}, {"main.npdm", 0x20}, {"", 1}};
    expect(!plans(empty), "an empty name");
    constexpr ListedFile large[] = {{"main", DonorFileSizeLimit + 1}, {"main.npdm", 0x20}};
    expect(!plans(large), "a file over the size limit");
    constexpr ListedFile fits[] = {{"main", DonorFileSizeLimit}, {"main.npdm", 0x20}};
    expect(plans(fits), "a file at the size limit");
    expect(!plans(fits, DonorFileSizeLimit + 1), "hbloader over the size limit");

    // A title without its own rtld gains one file: 24 listed is one too many.
    DonorFile title[DonorFileLimit + 1] = {};
    std::strcpy(title[0].name, "main");
    std::strcpy(title[1].name, "main.npdm");
    for (u32 index = 2; index < DonorFileLimit + 1; index++) {
        std::snprintf(title[index].name, sizeof(title[index].name), "subsdk%u", index);
    }
    static DonorPlan plan;
    expect(!planDonor(title, DonorFileLimit, 0x100, plan), "25 files with hbloader");
    expect(planDonor(title, DonorFileLimit - 1, 0x100, plan), "24 files with hbloader");
    std::strcpy(title[DonorFileLimit - 1].name, "rtld");
    expect(planDonor(title, DonorFileLimit, 0x100, plan), "24 listed with the title's rtld");
    expect(!planDonor(title, DonorFileLimit + 1, 0x100, plan), "more listed than the limit");
}

void checkNames() {
    expect(isDonorName("main.npdm") && isDonorName("...") && isDonorName("~"), "names taken");
    char longest[DonorNameLimit + 2] = {};
    std::memset(longest, 'x', DonorNameLimit);
    expect(isDonorName(longest), "the longest name");
    longest[DonorNameLimit] = 'x';
    expect(!isDonorName(longest), "a name over the limit");
    const char* refused[] = {"", ".", "..", "a b", "a\\b", "c:x", "\x7f", "tab\t"};
    for (const char* name : refused) expect(!isDonorName(name), name);
    expect(!isDonorName(nullptr), "no name");

    expect(donorBefore("rtld", "main") && donorBefore("main", "subsdk0") &&
               donorBefore("subsdk0", "sdk") && donorBefore("sdk", "a") &&
               donorBefore("zz", "main.npdm"),
           "rank order");
    expect(donorBefore("subsdk9", "subsdk10") && !donorBefore("subsdk10", "subsdk9"),
           "subsdk by value");
    expect(donorBefore("subsdk01", "subsdk1") && !donorBefore("subsdk1", "subsdk01"),
           "equal values by name");
    expect(!donorBefore("main", "main"), "a name is not before itself");

    expect(!std::strcmp(donorMagic("main.npdm"), "META"), "policy magic");
    const char* modules[] = {"rtld", "main", "sdk", "subsdk0", "subsdk", "subsdkx"};
    for (const char* name : modules) {
        expect(donorMagic(name) && !std::strcmp(donorMagic(name), "NSO0"), name);
    }
    expect(!donorMagic("sdk0") && !donorMagic("Main") && !donorMagic("zz"), "no magic");

    u8 meta[MetaFlagsOffset + 1] = {'M', 'E', 'T', 'A'};
    meta[MetaFlagsOffset] = 0x3f;
    expect(isDonorPolicy(meta, sizeof(meta)), "a 64-bit policy");
    expect(!isDonorPolicy(meta, sizeof(meta) - 1), "a short policy");
    meta[MetaFlagsOffset] = 0x3e;
    expect(!isDonorPolicy(meta, sizeof(meta)), "a 32-bit policy");
    meta[MetaFlagsOffset] = 1;
    meta[3] = 'B';
    expect(!isDonorPolicy(meta, sizeof(meta)), "not META");
}

